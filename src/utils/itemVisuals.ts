const normalizeName = (value: string) =>
  value
    .toLowerCase()
    .replace(/[【】《》「」『』（）()\[\]{}]/g, '')
    .replace(/\s+/g, '')
    .replace(/[·•,，。!！?？:：'"“”‘’]/g, '');

