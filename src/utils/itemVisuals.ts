export const getTypeVisual = (type?: string): ItemVisual => typeFallbacks[type || 'misc'] || typeFallbacks.misc;

export const getItemVisual = (itemOrName: Item | string, typeHint?: string): ItemVisual => {
  const name = typeof itemOrName === 'string' ? itemOrName : itemOrName.name;
  const type = typeof itemOrName === 'string' ? typeHint : itemOrName.type;
  const normalized = normalizeName(name || '');

  for (const rule of visualRules) {
    if (rule.keywords.some(keyword => normalized.includes(normalizeName(keyword)))) {
      return rule;
    }
  }

  return getTypeVisual(type);
};

export const getItemTypeLabel = (type?: string) => typeLabels[type || 'misc'] || '杂物';

export const getItemVisualSummary = (item: Item | string, typeHint?: string) => {
  const visual = getItemVisual(item, typeHint);
  return `${visual.emoji} ${visual.label}`;
};

export const getItemIconAsset = (itemOrName: Item | string, typeHint?: string) => {
  return getItemVisual(itemOrName, typeHint).iconAsset;
};
